    private void btnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarActionPerformed
    
    Date dataInicial = jCalendarDataInicial.getDate();
    Date dataFinal = jCalendarDataFinal.getDate();
         
    try {

    String tipo = cbTipoRelatorio.getSelectedItem().toString();

    String sql;
    
    
    if (tipo.equals("Venda via Pix")) {
    tipo = "Pix";
} else if (tipo.equals("Vendas em Dinheiro")) {
    tipo = "Dinheiro";
} else if (tipo.equals("Cartão de Débito")) {
    tipo = "Cartão Débito";
} else if (tipo.equals("Cartão de Crédito")) {
    tipo = "Cartão Crédito";
}

    
    
    
    
    

    if (tipo.equals("Todos") || tipo.equals("Total de Vendas")) {

        sql = "SELECT v.id, "
                + "v.data_venda, "
                + "c.nome AS Cliente, "
                + "v.forma_pagamento, "
                + "v.total_venda "
                + "FROM tb_vendas v "
                + "INNER JOIN tb_clientes c "
                + "ON c.id = v.cliente_id "
                + "WHERE v.data_venda BETWEEN ? AND ? "
                + "ORDER BY v.data_venda";

    } else {

        sql = "SELECT v.id, "
                + "v.data_venda, "
                + "c.nome AS Cliente, "
                + "v.forma_pagamento, "
                + "v.total_venda "
                + "FROM tb_vendas v "
                + "INNER JOIN tb_clientes c "
                + "ON c.id = v.cliente_id "
                + "WHERE v.data_venda BETWEEN ? AND ? "
                + "AND v.forma_pagamento = ? "
                + "ORDER BY v.data_venda";
    }

    PreparedStatement pst = conn.prepareStatement(sql);

    pst.setDate(1, new java.sql.Date(dataInicial.getTime()));
    pst.setDate(2, new java.sql.Date(dataFinal.getTime()));

    if (!tipo.equals("Todos") && !tipo.equals("Total de Vendas")) {
        pst.setString(3, tipo);
    }

    ResultSet rs = pst.executeQuery();

    DefaultTableModel modelo = (DefaultTableModel) tbRelatorioFinanceiro.getModel();
    modelo.setRowCount(0);

    double total = 0;

    while (rs.next()) {

        modelo.addRow(new Object[]{
            rs.getInt("id"),
            new java.text.SimpleDateFormat("dd/MM/yyyy").format(rs.getDate("data_venda")),
            rs.getString("Cliente"),
            rs.getString("forma_pagamento"),
            String.format("R$ %,.2f",rs.getDouble("total_venda")).replace(",", "X").replace(".", ",").replace("X",".")
        });

        total += rs.getDouble("total_venda");
    }

    txtTotalVendas.setText(String.format("R$ %.2f", total));

} catch (Exception e) {
    JOptionPane.showMessageDialog(null, e.getMessage());
}

        
        
        
    }//GEN-LAST:event_btnPesquisarActionPerformed

