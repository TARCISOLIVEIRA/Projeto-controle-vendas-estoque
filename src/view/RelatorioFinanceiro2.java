      private void pesquisar(Date dataInicial, Date dataFinal){
        
        try {

        String sql = "SELECT\n" +
"    v.id AS Venda,\n" +
"    v.data_venda AS Data,\n" +
"    c.nome AS Cliente,\n" +
"    v.forma_pagamento AS \"Forma de Pagamento\",\n" +
"    v.total_venda AS \"Total (R$)\"\n" +
"FROM tb_vendas v\n" +
"INNER JOIN tb_clientes c\n" +
"    ON c.id = v.cliente_id\n" +
"WHERE v.data_venda BETWEEN ? AND ?\n" +
"ORDER BY v.data_venda     ";
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setDate(1, new java.sql.Date(dataInicial.getTime()));
        pst.setDate(2, new java.sql.Date(dataFinal.getTime()));

        ResultSet rs = pst.executeQuery();

        DefaultTableModel modelo = (DefaultTableModel) tbRelatorioFinanceiro.getModel();
        modelo.setRowCount(0);

        while (rs.next()) {

            modelo.addRow(new Object[]{
                rs.getInt("Venda"),
                new java.text.SimpleDateFormat("dd/MM/yyyy").format(rs.getDate("Data")),

               
                //rs.getDate("Data"),
                rs.getString("Cliente"),
                rs.getString("Forma de Pagamento"),
                
                String.format("R$ %,.2f",rs.getDouble("Total (R$)")).replace(",", "X").replace(".", ",").replace("X",".")
               // rs.getDouble("Total (R$)")
            });

        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, e.getMessage());
    }
       
       
       
       
       
       
       
       
   }
    
    
    
    
    
    
